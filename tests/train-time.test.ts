import { fixTrainTimes } from "../src/lib/rail.js";

/**
 * 發車／抵達時刻修正。
 *
 * 線上實測：班表寫著「0612 09:00→09:59」，模型抄對車次與發車，
 * 抵達卻自己算成 10:59，然後照著錯的時間排了一整天。
 */
const INDEX = {
  "0612": { depart: "09:00", arrive: "09:59" },
  "0145": { depart: "16:31", arrive: "17:18" },
  "0663": { depart: "16:46", arrive: "17:46" },
};

const cases: Array<[string, string, string]> = [
  [
    "台中高鐵站搭乘 0612 車次，09:00 發車，10:59 抵達台北站",
    "台中高鐵站搭乘 0612 車次，09:00 發車，09:59 抵達台北站",
    "抵達錯一小時 → 改對",
  ],
  [
    "搭乘高鐵 1210 班次（09:08 發車→09:54 抵達）",
    "搭乘高鐵 1210 班次（09:08 發車→09:54 抵達）",
    "車次不在班表裡 → 不動",
  ],
  [
    "台北高鐵站搭乘 0145 車次，16:31 發車，17:18 抵達台中站",
    "台北高鐵站搭乘 0145 車次，16:31 發車，17:18 抵達台中站",
    "本來就對 → 不動",
  ],
  [
    "搭乘 0612 車次，08:30 發車，09:30 抵達",
    "搭乘 0612 車次，09:00 發車，09:59 抵達",
    "發車與抵達都錯 → 都改",
  ],
  [
    "可搭 0145 車次或改搭 0663 車次，16:00 發車",
    "可搭 0145 車次或改搭 0663 車次，16:00 發車",
    "一句話兩個車次 → 對不出來，放過",
  ],
  [
    "從台北車站搭高鐵南下，約 47 分鐘抵達",
    "從台北車站搭高鐵南下，約 47 分鐘抵達",
    "沒有車次 → 不動",
  ],
  [
    "票價 700 元，09:00 發車",
    "票價 700 元，09:00 發車",
    "700 不是車次，不能被當成車次",
  ],
];

let pass = 0;
for (const [input, want, note] of cases) {
  const r = fixTrainTimes(input, INDEX);
  const ok = r.text === want;
  if (ok) pass++;
  console.log(`  ${ok ? "ok  " : "FAIL"} ${r.text === input ? "· 不動" : "✎ 已修正"}  ${note}`);
  if (!ok) {
    console.log(`        得到：${r.text}`);
    console.log(`        期望：${want}`);
  }
  for (const n of r.notes) console.log(`        → ${n}`);
}
console.log(`\n${pass}/${cases.length} 通過`);
process.exit(pass === cases.length ? 0 : 1);
